/** Trimmed nickname, or null when empty/too long. */
export function normalizeNickname(raw: string): string | null {
	const trimmed = raw.trim();
	if (trimmed.length < 1 || trimmed.length > MAX_NICKNAME_LENGTH) return null;
	return trimmed;
}

function createEmptyProgress(): SeatProgress {
	return {
		checkedObjectiveCounts: {},
		scheme: null,
		schemeDraft: { factionId: null, intelligence: null },
		schemeRevealed: false
	};
}

export function createEmptySeat(
	nickname: string,
	tokenHash: string,
	army: PickedArmy
): OnlineSeatState {
	return {
		nickname,
		tokenHash,
		army,
		// A Standard registration is already a legal match list; a Roster one has to be cut down.
		combatArmy: pickedArmyFormat(army) === 'standard' ? army : null,
		leader: null,
		ready: false,
		progress: createEmptyProgress(),
		drawnSchemeIds: []
	};
}

/** What the creating player brings: the mission to play and the army they field. */
export type OnlineGameSetup = {
	season: string;
	missionId: string;
	army: PickedArmy;
};

export function createOnlineGame(
	id: string,
	leaderNickname: string,
	leaderTokenHash: string,
	createdAt: string,
	setup: OnlineGameSetup
): OnlineGameState {
	return {
		id,
		status: 'lobby',
		player1: createEmptySeat(leaderNickname, leaderTokenHash, setup.army),
		player2: null,
		pendingJoin: null,
		season: setup.season,
		missionId: setup.missionId,
		currentRound: MIN_ROUND,
		phase: 'playing',
		roundSnapshots: {},
		winner: null,
		resultSummary: null,
		tournament: null,
		createdAt,
		updatedAt: createdAt
	};
}

/** One of the two players a tournament seats at a table: who they are and what they registered. */
export type TournamentGameSeat = {
	nickname: string;
	tokenHash: string;
	army: PickedArmy;
};

/**
 * A table's match, born with both seats filled: a tournament already decided this pairing, so
 * there is no join request to approve and no invite code to share. The mission comes from the
 * round and each player's army from their tournament registration — which is a Roster, so both
 * seats start the match by cutting a list down, exactly like the free online flow.
 *
 * Seat order is the table's occupant order, which is what makes `player1` (the game's leader)
 * stable for the whole match.
 */
export function createTournamentGame(
	id: string,
	createdAt: string,
	mission: { season: string; missionId: string },
	tournament: OnlineGameTournamentRef,
	seats: readonly [TournamentGameSeat, TournamentGameSeat]
): OnlineGameState {
	const [first, second] = seats;
	const state = createOnlineGame(id, first.nickname, first.tokenHash, createdAt, {
		season: mission.season,
		missionId: mission.missionId,
		army: first.army
	});
	return {
		...state,
		player2: createEmptySeat(second.nickname, second.tokenHash, second.army),
		tournament
	};
}

/**
 * Replaces a seat's token hash. A tournament player whose device lost its session proves who they
 * are with their tournament token instead, and gets back in with a freshly minted one — the old
 * token dies with it, which is the same "one token holds one seat" rule a join lives by.
 */
export function reseatToken(
	state: OnlineGameState,
	seat: PlayerKey,
	tokenHash: string
): OnlineGameState {
	return updateSeat(state, seat, (current) => ({ ...current, tokenHash }));
}

function updateSeat(
	state: OnlineGameState,
	seat: PlayerKey,
	updater: (s: OnlineSeatState) => OnlineSeatState
): OnlineGameState {
	const current = state[seat];
	if (!current) return state;
	return { ...state, [seat]: updater(current) };
}

/** Which seat owns a given (already hashed) token, if any. */
export function seatForTokenHash(state: OnlineGameState, tokenHash: string): PlayerKey | null {
	if (state.player1.tokenHash === tokenHash) return 'player1';
	if (state.player2?.tokenHash === tokenHash) return 'player2';
	return null;
}

// --- lobby: join flow ---

export function canRequestJoin(state: OnlineGameState): boolean {
	return state.status === 'lobby' && !state.player2 && !state.pendingJoin;
}

export function requestJoin(
	state: OnlineGameState,
	nickname: string,
	tokenHash: string,
	army: PickedArmy
): OnlineGameState {
	if (!canRequestJoin(state)) return state;
	return { ...state, pendingJoin: { nickname, tokenHash, army } };
}

/** Seat 2 takes over the pending request's nickname, token hash and army. */
export function acceptJoin(state: OnlineGameState): OnlineGameState {
	if (state.status !== 'lobby' || state.player2 || !state.pendingJoin) return state;
	return {
		...state,
		player2: createEmptySeat(
			state.pendingJoin.nickname,
			state.pendingJoin.tokenHash,
			state.pendingJoin.army
		),
		pendingJoin: null
	};
}

export function denyJoin(state: OnlineGameState): OnlineGameState {
	if (!state.pendingJoin) return state;
	return { ...state, pendingJoin: null };
}

// --- prep: the combat army ---

/** Whether a seat has a match list to field. */
export function isCombatReady(seat: OnlineSeatState): boolean {
	return seat.combatArmy !== null;
}

/** Both seats have a match list, which is what lets the leader leave the prep step. */
export function bothCombatReady(state: OnlineGameState): boolean {
	return isCombatReady(state.player1) && state.player2 !== null && isCombatReady(state.player2);
}

/**
 * Only a seat that registered a Roster army has anything to cut; a Standard registration is its
 * own combat army from the moment the seat is filled, and stays that way.
 */
export function canSetCombatArmy(state: OnlineGameState, seat: PlayerKey): boolean {
	if (state.status !== 'active' || state.phase !== 'prep') return false;
	const own = state[seat];
	return own !== null && pickedArmyFormat(own.army) === 'roster';
}

export function setCombatArmy(
	state: OnlineGameState,
	seat: PlayerKey,
	army: PickedArmy
): OnlineGameState {
	if (!canSetCombatArmy(state, seat)) return state;
	// A new list renumbers its copies on decode, so a leader chosen from the old one would dangle.
	return updateSeat(state, seat, (s) => ({ ...s, combatArmy: army, leader: null }));
}

/**
 * Any copy of the combat army may be the Leader — Stratagems are restricted *to* the Leader, not
 * the Leader to Stratagem-bearers — so the only precondition is having a list to choose from.
 */
export function canSetLeader(state: OnlineGameState, seat: PlayerKey): boolean {
	if (state.status !== 'active' || state.phase !== 'prep') return false;
	const own = state[seat];
	return own !== null && own.combatArmy !== null;
}

export function setLeader(
	state: OnlineGameState,
	seat: PlayerKey,
	leader: SeatLeader | null
): OnlineGameState {
	if (!canSetLeader(state, seat)) return state;
	return updateSeat(state, seat, (s) => ({ ...s, leader }));
}

/**
 * The Leader's M and INT are published from Scheme selection on, because that is where the
 * initiative roll that needs them sits. The Leader's identity never is.
 */
export function isLeaderStatsRevealed(state: OnlineGameState): boolean {
	return state.status !== 'lobby' && state.phase !== 'armies' && state.phase !== 'prep';
}

/** Both seats have named a Leader, which is what gives a seat its intelligence. */
export function bothLeadersAssigned(state: OnlineGameState): boolean {
	return state.player1.leader !== null && state.player2 !== null && state.player2.leader !== null;
}

export function canLeavePrep(state: OnlineGameState): boolean {
	return (
		state.status === 'active' &&
		state.phase === 'prep' &&
		bothCombatReady(state) &&
		bothLeadersAssigned(state)
	);
}

/**
 * Prep → Scheme setup. There is no way back: a cut is final once the table moves on.
 *
 * Both halves of the Scheme draft are derived here rather than typed in later: the faction from
 * the combat army, the intelligence from the Leader's declared INT. Nothing about the draw is left
 * for a client to choose, because the draw count is the one thing a player could otherwise
 * inflate.
 */
export function leavePrep(state: OnlineGameState): OnlineGameState {
	if (!canLeavePrep(state) || state.player2 === null) return state;
	const seed = (seat: OnlineSeatState): OnlineSeatState => ({
		...seat,
		progress: {
			...seat.progress,
			schemeDraft: {
				factionId: schemeFactionForArmy((seat.combatArmy ?? seat.army).factionId),
				intelligence: seat.leader?.int ?? null
			}
		}
	});
	return { ...state, phase: 'setup', player1: seed(state.player1), player2: seed(state.player2) };
}

// --- setup: faction and Scheme ---

/**
 * Scheme setup happens in the `setup` phase, after both seats have a match list and a Leader —
 * the army fixes the faction and the Leader fixes the intelligence, so there is nothing left to
 * choose but the Scheme itself.
 */
export function canEditSetup(state: OnlineGameState): boolean {
	return state.status === 'active' && state.phase === 'setup';
}

export function setSeatDrawnSchemes(
	state: OnlineGameState,
	seat: PlayerKey,
	schemeIds: string[]
): OnlineGameState {
	if (!canEditSetup(state)) return state;
	return updateSeat(state, seat, (s) => ({ ...s, drawnSchemeIds: schemeIds }));
}

export function canDrawSchemes(state: OnlineGameState, seat: PlayerKey): boolean {
	const current = state[seat];
	if (!canEditSetup(state) || !current) return false;
	const { factionId, intelligence } = current.progress.schemeDraft;
	return factionId !== null && intelligence !== null;
}

/** Only cards from the seat's own drawn hand may be chosen. */
export function canChooseSeatScheme(
	state: OnlineGameState,
	seat: PlayerKey,
	schemeId: string
): boolean {
	const current = state[seat];
	if (!canEditSetup(state) || !current) return false;
	const { factionId, intelligence } = current.progress.schemeDraft;
	return factionId !== null && intelligence !== null && current.drawnSchemeIds.includes(schemeId);
}

/** Picks a scheme from the seat's drawn hand and discards the rest of the hand. */
export function chooseSeatScheme(
	state: OnlineGameState,
	seat: PlayerKey,
	schemeId: string
): OnlineGameState {
	if (!canChooseSeatScheme(state, seat, schemeId)) return state;
	const { factionId, intelligence } = state[seat]!.progress.schemeDraft;
	return updateSeat(state, seat, (s) => ({
		...s,
		drawnSchemeIds: [],
		progress: { ...s.progress, scheme: chooseScheme(schemeId, factionId!, intelligence!) }
	}));
}

export function clearSeatScheme(state: OnlineGameState, seat: PlayerKey): OnlineGameState {
	if (!canEditSetup(state)) return state;
	return updateSeat(state, seat, (s) => ({ ...s, progress: { ...s.progress, scheme: null } }));
}

// --- lobby: readiness ---

/** Readiness is a lobby-only signal, and a seat may only flip its own. */
export function canToggleReady(state: OnlineGameState, seat: PlayerKey): boolean {
	return state.status === 'lobby' && state[seat] !== null;
}

export function toggleReady(state: OnlineGameState, seat: PlayerKey): OnlineGameState {
	if (!canToggleReady(state, seat)) return state;
	return updateSeat(state, seat, (s) => ({ ...s, ready: !s.ready }));
}

/** Both seats say they are set to start. */
export function bothReady(state: OnlineGameState): boolean {
	return state.player1.ready && state.player2 !== null && state.player2.ready;
}

/** Both seats have committed a Scheme. */
export function bothSchemesChosen(state: OnlineGameState): boolean {
	return (
		state.player1.progress.scheme !== null &&
		state.player2 !== null &&
		state.player2.progress.scheme !== null
	);
}

export function canStartGame(state: OnlineGameState): boolean {
	return (
		state.status === 'lobby' &&
		state.missionId !== null &&
		state.player2 !== null &&
		bothReady(state)
	);
}

/**
 * Start Game opens the army reveal, not round 1 — the rulebook shows both factions and rosters
 * before anyone builds a party from theirs.
 */
export function startGame(state: OnlineGameState): OnlineGameState {
	if (!canStartGame(state)) return state;
	return { ...state, status: 'active', currentRound: MIN_ROUND, phase: 'armies' };
}

// --- armies: the roster reveal ---

/**
 * A roster is revealed once the game is running, and stays revealed — including after it finishes,
 * so the statistics screen can still show what was brought. A Standard registration is never
 * revealed here: for it the registered list *is* the match list, and the rulebook keeps parties
 * secret until deployment.
 */
export function isRosterRevealed(state: OnlineGameState): boolean {
	return state.status !== 'lobby';
}

export function canLeaveArmies(state: OnlineGameState): boolean {
	return state.status === 'active' && state.phase === 'armies';
}

/** The reveal → preparation. There is no way back: what was shown stays shown. */
export function leaveArmies(state: OnlineGameState): OnlineGameState {
	if (!canLeaveArmies(state)) return state;
	return { ...state, phase: 'prep' };
}

export function canStartRounds(state: OnlineGameState): boolean {
	return state.status === 'active' && state.phase === 'setup' && bothSchemesChosen(state);
}

/**
 * Scheme setup → round 1. A running round carries no sub-phase: everything a round needs —
 * objectives, the reveal, scheme boxes — is editable within it, as on a physical table.
 */
export function startRounds(state: OnlineGameState): OnlineGameState {
	if (!canStartRounds(state)) return state;
	return { ...state, phase: 'playing' };
}

// --- active: rounds ---

/** A round is in progress: its objectives and scheme boxes are editable by their owners. */
export function isRoundRunning(state: OnlineGameState): boolean {
	return state.status === 'active' && state.phase === 'playing';
}

/**
 * A seat may publish its board once the round is running and it has a combat army to field —
 * and only once: the board's identity must not shift under a match being played. The composition
 * opens at play because the models are on the table by then; the importable code never travels.
 * A finished match still accepts the publish: a device that reconnects after the last round must
 * be able to field its half of the battle report.
 */
export function canPublishRoster(state: OnlineGameState, seat: PlayerKey): boolean {
	if (state.phase !== 'playing') return false;
	if (state.status !== 'active' && state.status !== 'finished') return false;
	const current = state[seat];
	if (!current || current.combatArmy === null) return false;
	return seatPublishedRoster(current) === null;
}

export function publishRoster(
	state: OnlineGameState,
	seat: PlayerKey,
	entries: ArmyEntry[]
): OnlineGameState {
	if (!canPublishRoster(state, seat)) return state;
	const current = state[seat]!;
	return { ...state, [seat]: { ...current, publishedRoster: entries } };
}

/** Bounds on a published board: a format cap of 125 points cannot field more copies than this. */
export const PUBLISHED_ROSTER_MAX = 60;
const PUBLISHED_ID_MAX = 64;

/**
 * The board a seat declares, parsed and bounded. Entry ids are the publisher's own - they are
 * what its device's flowers and vitality map key on, and the server cannot derive them from the
 * stored code - so they enter the state exactly as declared, only bounded in shape and size.
 */
export function parsePublishedRoster(raw: unknown): ArmyEntry[] | null {
	if (!Array.isArray(raw) || raw.length === 0 || raw.length > PUBLISHED_ROSTER_MAX) return null;
	const entries: ArmyEntry[] = [];
	for (const item of raw) {
		if (typeof item !== 'object' || item === null) return null;
		const body = item as Record<string, unknown>;
		if (typeof body.id !== 'string' || body.id.length > PUBLISHED_ID_MAX || body.id.length === 0)
			return null;
		if (typeof body.unitId !== 'string' || body.unitId.length > PUBLISHED_ID_MAX) return null;
		const entry: ArmyEntry = { id: body.id, unitId: body.unitId };
		if (body.mounted === true) entry.mounted = true;
		if (body.upgrades !== undefined) {
			if (!Array.isArray(body.upgrades) || body.upgrades.length > 16) return null;
			if (!body.upgrades.every((u) => typeof u === 'string' && u.length <= PUBLISHED_ID_MAX))
				return null;
			entry.upgrades = body.upgrades as string[];
		}
		if (body.spellcraftChoices !== undefined) {
			if (typeof body.spellcraftChoices !== 'object' || body.spellcraftChoices === null)
				return null;
			const choices: Record<string, string> = {};
			for (const [key, value] of Object.entries(body.spellcraftChoices)) {
				if (typeof value !== 'string' || value.length > PUBLISHED_ID_MAX) return null;
				choices[key] = value;
			}
			entry.spellcraftChoices = choices;
		}
		if (body.upgradeChoices !== undefined) {
			if (typeof body.upgradeChoices !== 'object' || body.upgradeChoices === null) return null;
			const choices: Record<string, ArmyUpgradeChoice> = {};
			for (const [key, value] of Object.entries(body.upgradeChoices)) {
				if (typeof value !== 'object' || value === null) return null;
				const choice = value as Record<string, unknown>;
				if (typeof choice.option !== 'string' || choice.option.length > PUBLISHED_ID_MAX)
					return null;
				const parsed: ArmyUpgradeChoice = { option: choice.option };
				if (choice.itemId !== undefined) {
					if (typeof choice.itemId !== 'string' || choice.itemId.length > PUBLISHED_ID_MAX)
						return null;
					parsed.itemId = choice.itemId;
				}
				if (choice.removedElement !== undefined) {
					if (
						typeof choice.removedElement !== 'string' ||
						choice.removedElement.length > PUBLISHED_ID_MAX
					)
						return null;
					parsed.removedElement = choice.removedElement;
				}
				choices[key] = parsed;
			}
			entry.upgradeChoices = choices;
		}
		entries.push(entry);
	}
	return entries;
}

/**
 * Reveals this seat's scheme, immediately and permanently. The reveal is each player's own
 * decision at any moment of a running round — not an intent the leader commits on their behalf at
 * a phase change — so there is nothing to toggle and nothing to take back.
 */
export function canRevealSeatScheme(state: OnlineGameState, seat: PlayerKey): boolean {
	if (!isRoundRunning(state)) return false;
	const current = state[seat];
	return !!current?.progress.scheme && !current.progress.schemeRevealed;
}

export function revealSeatScheme(state: OnlineGameState, seat: PlayerKey): OnlineGameState {
	if (!canRevealSeatScheme(state, seat)) return state;
	return updateSeat(state, seat, (s) => ({
		...s,
		progress: { ...s.progress, schemeRevealed: true }
	}));
}

/** Objectives are editable only by their owner, at any point in a running round. */
export function setSeatObjectiveChecked(
	state: OnlineGameState,
	seat: PlayerKey,
	objectiveId: string,
	checkedCount: number,
	maxCount: number
): OnlineGameState {
	if (!isRoundRunning(state)) return state;
	const clamped = Math.max(0, Math.min(checkedCount, maxCount));
	return updateSeat(state, seat, (s) => ({
		...s,
		progress: {
			...s.progress,
			checkedObjectiveCounts: { ...s.progress.checkedObjectiveCounts, [objectiveId]: clamped }
		}
	}));
}

/** Scheme boxes are editable only by their owner, in a running round, and only once revealed. */
export function canScoreSeatScheme(state: OnlineGameState, seat: PlayerKey): boolean {
	if (!isRoundRunning(state)) return false;
	const current = state[seat];
	return !!current?.progress.scheme && current.progress.schemeRevealed;
}

export function setSeatSchemeChecked(
	state: OnlineGameState,
	seat: PlayerKey,
	checkedIncrements: number,
	maxIncrements: number
): OnlineGameState {
	if (!canScoreSeatScheme(state, seat)) return state;
	return updateSeat(state, seat, (s) => ({
		...s,
		progress: {
			...s.progress,
			scheme: setSchemeChecked(s.progress.scheme!, checkedIncrements, maxIncrements)
		}
	}));
}

/** Snapshots the current round's VP and opens the next one. Round 5 concludes instead. */
export function snapshotAndProceed(state: OnlineGameState, vp: RoundSnapshot): OnlineGameState {
	if (!isRoundRunning(state)) return state;
	if (state.currentRound >= MAX_ROUND) return state;
	return {
		...state,
		roundSnapshots: { ...state.roundSnapshots, [state.currentRound]: vp },
		currentRound: state.currentRound + 1,
		phase: 'playing'
	};
}

export function finishGame(state: OnlineGameState, vp: RoundSnapshot): OnlineGameState {
	if (!isRoundRunning(state) || state.currentRound !== MAX_ROUND) {
		return state;
	}
	const revealAll = (seat: OnlineSeatState): OnlineSeatState => {
		if (!seat.progress.scheme) return seat;
		return {
			...seat,
			progress: { ...seat.progress, schemeRevealed: true }
		};
	};
	const winner: PlayerKey | 'draw' =
		vp.player1 > vp.player2 ? 'player1' : vp.player2 > vp.player1 ? 'player2' : 'draw';
	const factionOf = (seat: OnlineSeatState | null): string | null =>
		seat?.progress.scheme?.factionId ?? seat?.progress.schemeDraft.factionId ?? null;
	const resultSummary: ResultSummary = {
		winner,
		finalVp: vp,
		roundsPlayed: state.currentRound,
		season: state.season,
		missionId: state.missionId,
		factions: { player1: factionOf(state.player1), player2: factionOf(state.player2) }
	};
	return {
		...state,
		roundSnapshots: { ...state.roundSnapshots, [state.currentRound]: vp },
		player1: revealAll(state.player1),
		player2: state.player2 ? revealAll(state.player2) : null,
		winner,
		resultSummary,
		status: 'finished'
	};
}

/** Leader closes/abandons the game — allowed from lobby or active, never overrides finished. */
export function closeGame(state: OnlineGameState): OnlineGameState {
	if (state.status === 'finished' || state.status === 'closed') return state;
	return { ...state, status: 'closed' };
}

// --- visibility ---

export function toPublicSeat(seat: OnlineSeatState, reveal: SeatReveal): PublicSeatState {
	const { progress } = seat;
	return {
		nickname: seat.nickname,
		army: {
			name: seat.army.name,
			factionId: seat.army.factionId,
			format: pickedArmyFormat(seat.army)
		},
		// The roster's contents are public once revealed — but only a roster's. A Standard
		// registration is the match list itself and stays secret until deployment.
		rosterCode: reveal.roster && pickedArmyFormat(seat.army) === 'roster' ? seat.army.code : null,
		ready: seat.ready,
		combatReady: seat.combatArmy !== null,
		hasLeader: seat.leader !== null,
		leaderStats:
			reveal.leaderStats && seat.leader !== null
				? { m: seat.leader.m, int: seat.leader.int }
				: null,
		combatRoster: reveal.composition ? (seatPublishedRoster(seat) ?? null) : null,
		factionId: progress.scheme?.factionId ?? progress.schemeDraft.factionId,
		hasScheme: progress.scheme !== null,
		schemeRevealed: progress.schemeRevealed,
		revealedScheme: progress.scheme && progress.schemeRevealed ? progress.scheme : null,
		checkedObjectiveCounts: progress.checkedObjectiveCounts
	};
}

/** The server answers state requests with this per-seat filtered view. */
export function viewForSeat(state: OnlineGameState, seat: PlayerKey): OnlineGameView | null {
	const self = state[seat];
	if (!self) return null;
	const opponent = seat === 'player1' ? state.player2 : state.player1;
	const reveal: SeatReveal = {
		roster: isRosterRevealed(state),
		leaderStats: isLeaderStatsRevealed(state),
		// The composition opens with the round and stays open through the finish: the battle
		// report lists both armies, and the models were on the table anyway.
		composition: state.phase === 'playing' && state.status !== 'lobby' && state.status !== 'closed'
	};
	return {
		id: state.id,
		status: state.status,
		seat,
		phase: state.phase,
		currentRound: state.currentRound,
		season: state.season,
		missionId: state.missionId,
		pendingJoinNickname: state.pendingJoin?.nickname ?? null,
		roundSnapshots: state.roundSnapshots,
		winner: state.winner,
		resultSummary: state.resultSummary,
		tournament: onlineGameTournament(state),
		self,
		opponent: opponent ? toPublicSeat(opponent, reveal) : null
	};
}
