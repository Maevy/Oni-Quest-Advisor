import {
	pdfTextWidth,
	pdfWrapText,
	PDF_PAGE_HEIGHT,
	PDF_PAGE_WIDTH,
	type PdfColor,
	type PdfOp
} from './pdf';
import type { BattleReportStat } from './battleReport';

/**
 * The shared layout kit for the generated reports (battle and tournament): an A4 page flow with
 * margins, a heading rule, wrapped body text and ranking tables. Both reports are the same kind
 * of document - sections of text over a cursor that breaks pages - so the primitives live here
 * and the report modules only decide what goes where.
 */

export const REPORT_PAGE_WIDTH = PDF_PAGE_WIDTH;
export const REPORT_PAGE_HEIGHT = PDF_PAGE_HEIGHT;
export const REPORT_MARGIN = 48;
export const REPORT_CONTENT_WIDTH = PDF_PAGE_WIDTH - REPORT_MARGIN * 2;
const TOP = 56;
const BOTTOM = PDF_PAGE_HEIGHT - 56;
export const REPORT_INK: PdfColor = [0.1, 0.12, 0.18];
export const REPORT_MUTED: PdfColor = [0.42, 0.46, 0.55];
export const REPORT_ACCENT: PdfColor = [0.05, 0.35, 0.55];
const RULE: PdfColor = [0.72, 0.76, 0.82];

export type ReportLayout = { pages: PdfOp[][]; y: number };

export function newReportLayout(): ReportLayout {
	const layout: ReportLayout = { pages: [], y: TOP };
	newReportPage(layout);
	return layout;
}

export function newReportPage(layout: ReportLayout): void {
	layout.pages.push([]);
	layout.y = TOP;
}

export function putOp(layout: ReportLayout, op: PdfOp): void {
	layout.pages[layout.pages.length - 1].push(op);
}

export function ensureSpace(layout: ReportLayout, needed: number): void {
	if (layout.y + needed > BOTTOM) newReportPage(layout);
}

export function drawText(
	layout: ReportLayout,
	text: string,
	options: {
		size?: number;
		font?: 'helvetica' | 'helvetica-bold';
		color?: PdfColor;
		indent?: number;
		maxWidth?: number;
		leading?: number;
	} = {}
): void {
	const size = options.size ?? 9;
	const font = options.font ?? 'helvetica';
	const indent = options.indent ?? 0;
	const maxWidth = options.maxWidth ?? REPORT_CONTENT_WIDTH - indent;
	const leading = options.leading ?? size * 1.35;
	for (const line of pdfWrapText(text, font, size, maxWidth)) {
		ensureSpace(layout, leading);
		putOp(layout, {
			kind: 'text',
			x: REPORT_MARGIN + indent,
			y: layout.y + size * 0.8,
			text: line,
			font,
			size,
			color: options.color ?? REPORT_INK
		});
		layout.y += leading;
	}
}

export function drawHeading(layout: ReportLayout, text: string): void {
	ensureSpace(layout, 34);
	layout.y += 8;
	putOp(layout, {
		kind: 'text',
		x: REPORT_MARGIN,
		y: layout.y + 8,
		text: text.toUpperCase(),
		font: 'helvetica-bold',
		size: 11,
		color: REPORT_ACCENT
	});
	layout.y += 15;
	putOp(layout, {
		kind: 'line',
		x1: REPORT_MARGIN,
		y1: layout.y,
		x2: REPORT_MARGIN + REPORT_CONTENT_WIDTH,
		y2: layout.y,
		width: 0.8,
		color: REPORT_ACCENT
	});
	layout.y += 8;
}

/** One ranking: position, name on the left, the total right-aligned in the accent colour. */
export function drawStatTable(
	layout: ReportLayout,
	title: string,
	stats: BattleReportStat[],
	unit: string,
	emptyText?: string
): void {
	drawHeading(layout, title);
	if (stats.length === 0) {
		drawText(layout, emptyText ?? `No ${unit} was recorded.`, { color: REPORT_MUTED });
		return;
	}
	for (const [index, stat] of stats.entries()) {
		ensureSpace(layout, 13);
		putOp(layout, {
			kind: 'text',
			x: REPORT_MARGIN + 6,
			y: layout.y + 7.5,
			text: `${index + 1}.`,
			font: 'helvetica',
			size: 9,
			color: REPORT_MUTED
		});
		putOp(layout, {
			kind: 'text',
			x: REPORT_MARGIN + 26,
			y: layout.y + 7.5,
			text: stat.name,
			font: 'helvetica',
			size: 9,
			color: REPORT_INK
		});
		const total = `${stat.total} ${unit}`;
		putOp(layout, {
			kind: 'text',
			x: REPORT_MARGIN + REPORT_CONTENT_WIDTH - pdfTextWidth(total, 'helvetica-bold', 9),
			y: layout.y + 7.5,
			text: total,
			font: 'helvetica-bold',
			size: 9,
			color: REPORT_ACCENT
		});
		layout.y += 13;
	}
}

/** The shared footer, stamped on every page once the page count is known. */
export function drawReportFooters(layout: ReportLayout): void {
	const pageCount = layout.pages.length;
	layout.pages.forEach((page, index) => {
		const footerY = PDF_PAGE_HEIGHT - 34;
		page.push({
			kind: 'line',
			x1: REPORT_MARGIN,
			y1: footerY - 8,
			x2: REPORT_MARGIN + REPORT_CONTENT_WIDTH,
			y2: footerY - 8,
			width: 0.6,
			color: RULE
		});
		page.push({
			kind: 'text',
			x: REPORT_MARGIN,
			y: footerY,
			text: 'Generated by Oni Quest Advisor - not persisted on any server',
			font: 'helvetica',
			size: 7.5,
			color: REPORT_MUTED
		});
		const label = `Page ${index + 1} of ${pageCount}`;
		page.push({
			kind: 'text',
			x: REPORT_MARGIN + REPORT_CONTENT_WIDTH - pdfTextWidth(label, 'helvetica', 7.5),
			y: footerY,
			text: label,
			font: 'helvetica',
			size: 7.5,
			color: REPORT_MUTED
		});
	});
}
